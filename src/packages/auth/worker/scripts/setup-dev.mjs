#!/usr/bin/env node
/**
 * Auto-fills auth/worker/.dev.vars from the root .env — so `pnpm dev` works immediately for
 * `/v1/data/profiles` without any manual copy-pasting. Re-runnable: values present in .env always
 * overwrite .dev.vars; keys .env doesn't provide keep whatever was filled in by hand.
 * Same self-contained shape as ../../llm/worker/scripts/setup-dev.mjs (no shared workspace
 * package in this repo — each worker keeps its own copy).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { ROOT_ENV, WORKER_ENV, publicSecretLeaks, rootEnvPicker } from './env.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const DEV_VARS = join(__dirname, '..', '.dev.vars');
const WRANGLER = join(__dirname, '..', 'wrangler.jsonc');

// ALLOWED_ORIGIN for LOCAL dev only (`.dev.vars`) — the Astro dev server's own origin (see root
// astro.config.mjs's `server.port: 5000`), distinct from wrangler.jsonc's own deploy-time placeholder.
const DEV_ALLOWED_ORIGIN = 'http://localhost:5000';

const nonEmpty = (obj) => Object.fromEntries(Object.entries(obj).filter(([, v]) => v));

function parseDevVars(text) {
    const out = {};
    for (const rawLine of text.split('\n')) {
        const line = rawLine.trim();
        if (!line || line.startsWith('#')) continue;
        const eq = line.indexOf('=');
        if (eq === -1) continue;
        out[line.slice(0, eq).trim()] = line.slice(eq + 1).trim().replace(/^"(.*)"$/, '$1');
    }
    return out;
}

/** Replaces `"VAR_NAME": "..."` inside wrangler.jsonc's `vars` block. No-op if `value` is falsy —
 *  an unset .env override should never blank out whatever's already hand-written. Regex
 *  string-replace, not JSON.parse+stringify, so wrangler.jsonc's own comments survive untouched. */
function syncWranglerVar(wranglerPath, varName, value) {
    if (!value) return false;
    const text = readFileSync(wranglerPath, 'utf8');
    const re = new RegExp(`("${varName}"\\s*:\\s*)"[^"]*"`);
    if (!re.test(text)) return false;
    const next = text.replace(re, `$1"${value}"`);
    if (next === text) return false;
    writeFileSync(wranglerPath, next);
    return true;
}

function main() {
    const pick = rootEnvPicker();
    if (!pick) {
        console.error(`[setup-dev] no .env found (root ${ROOT_ENV} or worker ${WORKER_ENV}) — nothing to derive, skipping.`);
        return;
    }
    for (const key of publicSecretLeaks(pick)) console.warn(`[setup-dev] ${key} in the root .env: remove it — PUBLIC_ vars can end up in the browser bundle (keep the unprefixed key, ideally in auth/worker/.env).`);
    const existing = existsSync(DEV_VARS) ? parseDevVars(readFileSync(DEV_VARS, 'utf8')) : {};

    const supabaseUrl = pick('PUBLIC_SUPABASE_URL');
    const serviceRoleKey = pick('SUPABASE_SERVICE_ROLE_KEY');

    // .env là nguồn chuẩn — giá trị có trong .env luôn đè .dev.vars cũ (đổi project Supabase không bị kẹt URL cũ).
    const fromEnv = nonEmpty({
        SUPABASE_URL: supabaseUrl,
        SUPABASE_SERVICE_ROLE_KEY: serviceRoleKey,
        PAYPAL_ENV: pick('PAYPAL_ENV'),
        PAYPAL_CLIENT_ID: pick('PAYPAL_CLIENT_ID', 'PUBLIC_PAYPAL_CLIENT_ID'),
        PAYPAL_CLIENT_SECRET: pick('PAYPAL_CLIENT_SECRET'),
        PAYPAL_WEBHOOK_ID: pick('PAYPAL_WEBHOOK_ID'),
        APP_URL: pick('APP_URL'),
        BILLING_SERVICE_KEY: pick('BILLING_SERVICE_KEY'),
        TG_BOT_TOKEN: pick('TG_BOT_TOKEN'),
        TG_CHAT_ID: pick('TG_CHAT_ID'),
    });
    const merged = { ALLOWED_ORIGIN: DEV_ALLOWED_ORIGIN, APP_URL: DEV_ALLOWED_ORIGIN, PAYPAL_ENV: 'sandbox', ...existing, ...fromEnv };

    const lines = [
        '# Auto-generated by scripts/setup-dev.mjs — key có trong root .env luôn bị đè khi chạy lại;',
        '# chỉ key .env không có mới giữ giá trị sửa tay ở đây.',
        '',
        '# Local dev only — wrangler.jsonc\'s copy is the prod placeholder, this overrides it here',
        `ALLOWED_ORIGIN="${merged.ALLOWED_ORIGIN || ''}"`,
        `SUPABASE_URL="${merged.SUPABASE_URL || ''}"`,
        '',
        '# Supabase service role key — from root .env\'s SUPABASE_SERVICE_ROLE_KEY (NOT PUBLIC_-prefixed)',
        `SUPABASE_SERVICE_ROLE_KEY="${merged.SUPABASE_SERVICE_ROLE_KEY || ''}"`,
        '',
        '# PayPal (/v1/billing/*) — sandbox app locally; PAYPAL_WEBHOOK_ID is the webhook registered for this app',
        `PAYPAL_ENV="${merged.PAYPAL_ENV || 'sandbox'}"`,
        `PAYPAL_CLIENT_ID="${merged.PAYPAL_CLIENT_ID || ''}"`,
        `PAYPAL_CLIENT_SECRET="${merged.PAYPAL_CLIENT_SECRET || ''}"`,
        `PAYPAL_WEBHOOK_ID="${merged.PAYPAL_WEBHOOK_ID || ''}"`,
        `APP_URL="${merged.APP_URL || ''}"`,
        '',
        '# Secret chung với llm (≥ 32 ký tự) — GET /v1/billing/peek/:userId; trống = route tắt',
        `BILLING_SERVICE_KEY="${merged.BILLING_SERVICE_KEY || ''}"`,
        '',
        '# Telegram báo đơn mới (src/invoices.ts) + Zap Share báo đã chuyển khoản (src/zap.ts) — trống = không gửi',
        `TG_BOT_TOKEN="${merged.TG_BOT_TOKEN || ''}"`,
        `TG_CHAT_ID="${merged.TG_CHAT_ID || ''}"`,
        '',
    ];
    writeFileSync(DEV_VARS, lines.join('\n'));

    // wrangler.jsonc's `vars.SUPABASE_URL` is what `wrangler deploy` actually ships (not
    // .dev.vars) — keep it in sync here too.
    if (syncWranglerVar(WRANGLER, 'SUPABASE_URL', supabaseUrl)) console.log('[setup-dev] wrangler.jsonc synced: SUPABASE_URL');

    console.log('[setup-dev] auth/worker/.dev.vars written.');
    if (merged.SUPABASE_URL && merged.SUPABASE_SERVICE_ROLE_KEY) console.log('  ready: /v1/data/profiles (Supabase configured)');
    else console.log('  missing: SUPABASE_URL/SUPABASE_SERVICE_ROLE_KEY — fill in the root .env first.');
    if (merged.PAYPAL_CLIENT_ID && merged.PAYPAL_CLIENT_SECRET) console.log(`  ready: /v1/billing (PayPal ${merged.PAYPAL_ENV})${merged.PAYPAL_WEBHOOK_ID ? '' : ' — PAYPAL_WEBHOOK_ID missing, webhook disabled'}`);
    else console.log('  missing: PAYPAL_CLIENT_ID/PAYPAL_CLIENT_SECRET — /v1/billing disabled (see hook/PURCHASE.rst → Setup).');
}

main();
